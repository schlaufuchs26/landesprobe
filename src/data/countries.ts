/**
 * The everyday standards of each country in the guessing pool.
 *
 * Columns (see `row` below): id, name, flag, plug types, mains voltage(s),
 * mains frequency/ies, driving side, emergency numbers, date format, decimal
 * separator, digit grouping, temperature scale, speed unit, colour TV standard,
 * first day of the week.
 *
 * Values are the ones a household actually meets: the plug that fits the wall,
 * the number you dial, the way the calendar page is printed. Where a country
 * runs two systems (Japan's 50 and 60 Hz, Brazil's 127 and 220 V) both are
 * listed, because that duality is the clue.
 *
 * `fact` explains the oddity of the countries a round can ask about; it is
 * shown on the reveal screen and is the part the player is meant to keep.
 */

export type PlugType =
  | "A"
  | "B"
  | "C"
  | "D"
  | "E"
  | "F"
  | "G"
  | "H"
  | "I"
  | "J"
  | "K"
  | "L"
  | "M"
  | "N";

type Driving = "left" | "right";
type Numbering = "west" | "indian";
type TvStandard = "PAL" | "SECAM" | "NTSC";

export type Country = {
  id: string;
  name: string;
  flag: string;
  plug: PlugType[];
  volts: number[];
  hertz: number[];
  driving: Driving;
  emergency: string[];
  /** Pattern with dd, mm and yyyy in the order the country prints them. */
  date: string;
  decimal: "," | ".";
  numbering: Numbering;
  temp: "C" | "F";
  speed: "km/h" | "mph";
  tv: TvStandard;
  weekStart: "Montag" | "Samstag" | "Sonntag";
  fact?: string;
  /** Other names a player may type (abbreviations, English exonyms). */
  aliases?: string[];
};

