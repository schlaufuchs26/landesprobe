export const COUNTRIES: Country[] = rows.map(
  ([
    id,
    name,
    flag,
    plug,
    volts,
    hertz,
    driving,
    emergency,
    date,
    decimal,
    numbering,
    temp,
    speed,
    tv,
    weekStart,
  ]) => {
    const country: Country = {
      id,
      name,
      flag,
      plug,
      volts,
      hertz,
      driving,
      emergency,
      date,
      decimal,
      numbering,
      temp,
      speed,
      tv,
      weekStart,
    };
    const fact = facts[id];
    if (fact) country.fact = fact;
    const alias = aliases[id];
    if (alias && alias.length > 0) country.aliases = alias;
    return country;
  },
);

export const COUNTRY_BY_ID: Map<string, Country> = new Map(
  COUNTRIES.map((country) => [country.id, country]),
);
